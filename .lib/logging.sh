#!/usr/bin/env bash
# ==============================================================================
# MODULE: logging (Единая система логирования)
# ==============================================================================
# Предоставляет стандартизированные функции для вывода сообщений в консоль.
# Подключается через source во всех скриптах проекта.

# Вывод информационного сообщения
log_info() {
  printf "[INFO] %s\n" "$*"
}

# Вывод предупреждения
log_warn() {
  printf "[WARN] %s\n" "$*" >&2
}

# Вывод ошибки
log_error() {
  printf "[ERROR] %s\n" "$*" >&2
}

# Вывод ошибки с аварийным завершением скрипта
log_fatal() {
  log_error "$*"
  exit 1
}

# Вывод заголовка секции
log_title() {
  printf "\n=== %s ===\n" "$*"
}

# Вывод шага выполнения
log_step() {
  printf "[*] %s\n" "$*"
}
